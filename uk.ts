/**
 * 🇺🇦 Ukrainian (@root/dto)
 *
 * TranslationSchema = DeepStringRecord<typeof en>
 * → TS перевіряє що всі ключі є (до листа включно),
 * але значення можуть бути будь-якими рядками.
 */

export type DeepStringRecord<T> = {
  [K in keyof T]: T[K] extends (...args: any[]) => any
  ? T[K]                          // ← функції зберігаємо як є
  : T[K] extends Record<string, unknown>
  ? DeepStringRecord<T[K]>      // ← рекурсія в об'єкти
  : string                      // ← листовий вузол → string
}

